require "aws-sdk-sns"
require "ai_core"
require_relative "alarm"
require_relative "evidence"
require_relative "k8s"

module Aiops
  # Lambda handler: an alarm fires -> gather evidence -> ask the model (through ai_core, so the answer is
  # validated like every other AI feature) -> post the analysis next to the alarm. It only reads and explains.
  module Rca
    RUNBOOKS = %w[high-error-rate high-latency queue-backlog].freeze

    class << self
      def handler(event:, context: nil)
        alarm = Alarm.from_sns(event)
        return { skipped: "not an alarm" } unless alarm
        return { skipped: "state #{alarm.state}" } unless alarm.firing?

        process(alarm)
      end

      def process(alarm, env: ENV, sns: Aws::SNS::Client.new, evidence: nil, client: AiCore.client)
        environment = env.fetch("ENVIRONMENT")
        evidence ||= Evidence.new(environment: environment, cluster: env.fetch("CLUSTER_NAME"), log_group: env.fetch("APP_LOG_GROUP"), k8s: k8s(env))

        result = client.run("analyze_incident", {
          alarm: { name: alarm.name, reason: alarm.reason, state_changed_at: alarm.changed_at },
          environment: environment, today: Time.now.utc.to_date.iso8601,
          evidence: evidence.collect(alarm), runbooks: RUNBOOKS
        })
        publish(sns, env.fetch("ALERTS_TOPIC_ARN"), alarm, result.output)
        result.output
      end

      private
        def k8s(env)
          return unless env["K8S_ACCESS"] == "true"

          K8s.new(cluster: env.fetch("CLUSTER_NAME"), region: env.fetch("AWS_REGION"))
        end

        def publish(sns, topic, alarm, analysis)
          body = [
            "Likely cause (#{analysis[:confidence]} confidence): #{analysis[:likely_cause]}",
            ("Runbook: docs/runbooks/#{analysis[:runbook]}.md" if analysis[:runbook]),
            "Suggested next steps:", *analysis[:suggested_actions].each_with_index.map { |action, index| "  #{index + 1}. #{action}" },
            "", "Generated by an AI model from CloudWatch, logs, traces and recent deploys. It can be wrong: check the evidence."
          ].compact.join("\n")

          sns.publish(
            topic_arn: topic, subject: "RCA: #{analysis[:summary]}"[0, 100], message: body,
            message_attributes: { "kind" => { data_type: "String", string_value: "rca" }, "alarm" => { data_type: "String", string_value: alarm.name } }
          )
        end
    end
  end
end
