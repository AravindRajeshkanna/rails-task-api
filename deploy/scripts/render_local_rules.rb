#!/usr/bin/env ruby
# The Prometheus rules docker compose loads (deploy/docker/prometheus-rules-local.yml), taken from the PrometheusRule objects Kubernetes applies, so that the dashboard
# and the alerts read the same on a laptop as they do in the cluster. Two of the dashboard's twenty queries are recording rules, and without the rules they are empty.
#
#   ruby deploy/scripts/render_local_rules.rb > deploy/docker/prometheus-rules-local.yml
#
# A spec fails when the committed file is not what this prints. Compose has no Alertmanager: the alerts show in Prometheus (http://localhost:9090/alerts) and go nowhere.
require "yaml"

root = File.expand_path("../..", __dir__)
sources = %w[task-api-rules.yaml task-api-slo.yaml].map { |name| "deploy/observability/prometheus/#{name}" }
groups = sources.flat_map { |source| YAML.load_file(File.join(root, source)).fetch("spec").fetch("groups") }

puts "# Generated by deploy/scripts/render_local_rules.rb from #{sources.join(' and ')}: do not edit, run it."
puts({ "groups" => groups }.to_yaml)
