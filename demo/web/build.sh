#!/usr/bin/env bash
# Builds the front end for hosting: copies the site to dist/ (without its tests) and writes dist/config.js for YOUR API. It is plain
# static files, so dist/ can go to any static host (GitHub Pages, S3 + CloudFront, Netlify, nginx).
#
#   API_URL=https://api.demo.example.com demo/web/build.sh
#   API_URL=https://api.example.com DEMO_LOGIN=false demo/web/build.sh      # no shared account on the sign-in form: anything that is not a demo
#
# API_URL is required and must be https (the page holds a bearer token; a browser also refuses an https page calling an http API). Then allow
# the origin that serves dist/ on the API: CORS_ORIGINS=https://demo.example.com (config/deploy.demo.yml).
set -euo pipefail
cd "$(dirname "$0")"

api_url="${API_URL:?Set API_URL to your API, e.g. https://api.demo.example.com}"
case "$api_url" in
  https://*) ;;
  http://localhost*|http://127.0.0.1*) echo "note: $api_url is only for running on your own machine" >&2 ;;
  *) echo "API_URL must start with https://" >&2; exit 2 ;;
esac
case "$api_url" in *[\"\'\\\ ]*) echo "API_URL must be a plain URL" >&2; exit 2 ;; esac

rm -rf dist
mkdir -p dist
cp -R index.html main.js style.css js dist/

if [ "${DEMO_LOGIN:-true}" = "false" ]; then
  login="null"
else
  login='{ email: "demo@example.com", password: "password123" }'
fi
cat > dist/config.js <<JS
// Generated by demo/web/build.sh. The API this page talks to, and the shared demo account the sign-in form offers (null: none).
export const config = {
  apiUrl: "${api_url%/}",
  demoLogin: ${login}
}
JS
echo "built demo/web/dist for ${api_url%/} ($(find dist -type f | wc -l | tr -d ' ') files)"
